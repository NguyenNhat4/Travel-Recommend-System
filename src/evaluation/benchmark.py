"""Leakage-conscious temporal evaluation for the recommender prototypes."""
from __future__ import annotations

import time
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Iterable

import numpy as np

from src.backend.app.application.ports import UnitIndex
from src.evaluation.recommender_prototypes import RankedProduct, Recommender, build_recommenders


@dataclass(frozen=True)
class LeaveOnePurchaseOut:
    train_by_user: dict[str, list[dict]]
    targets: dict[str, str]
    train_events: list[dict]
    target_times: dict[str, float]


def _time_key(event: dict, position: int) -> tuple[float, str, int]:
    value = event.get("timestamp")
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        timestamp = parsed.timestamp()
    except (TypeError, ValueError):
        timestamp = 0.0
    return (timestamp, str(event.get("productId") or ""), position)


def leave_one_purchase_out(events: list[dict], index: UnitIndex) -> LeaveOnePurchaseOut:
    """Hold out each user's latest resolvable purchase; all other events train models."""
    per_user: dict[str, list[tuple[int, dict]]] = {}
    for position, event in enumerate(events):
        user = event.get("cdpUserId")
        if user:
            per_user.setdefault(str(user), []).append((position, event))

    held_time: dict[str, float] = {}
    targets: dict[str, str] = {}
    for user, rows in per_user.items():
        purchases = [
            (position, event)
            for position, event in rows
            if event.get("eventName") == "purchase"
            and event.get("productId")
            and index.resolve(str(event["productId"])) is not None
        ]
        if not purchases:
            continue
        position, event = max(purchases, key=lambda pair: _time_key(pair[1], pair[0]))
        held_time[user] = _time_key(event, position)[0]
        targets[user] = index.units[index.resolve(str(event["productId"]))].product_id

    train_by_user = {
        user: [event for position, event in rows if user not in held_time or _time_key(event, position)[0] < held_time[user]]
        for user, rows in per_user.items()
    }
    train_events = [event for user, rows in train_by_user.items() for event in rows]
    return LeaveOnePurchaseOut(train_by_user=train_by_user, targets=targets, train_events=train_events, target_times=held_time)


def _product_id(value) -> str:
    return value.product_id if isinstance(value, RankedProduct) else str(value)


def benchmark_rows_have_p99(rows: list[dict]) -> bool:
    """Return whether cached rows were generated by the p99-aware evaluator."""
    return all("p99_runtime_ms" in row for row in rows)


def score_recommendations(
    recommendations: dict[str, Iterable[RankedProduct | str]],
    targets: dict[str, str],
    purchased_taxonomies: dict[str, set[str]],
    index: UnitIndex,
    latencies_ms: list[float] | None = None,
) -> dict[str, float]:
    """Calculate the shared metric set; unavailable items are measured, not filtered."""
    users = [user for user in targets if user in recommendations]
    if not users:
        return {
            "recall@10": 0.0,
            "recall@20": 0.0,
            "ndcg@10": 0.0,
            "cross_category_rate": 0.0,
            "availability_precision": 0.0,
            "catalog_coverage": 0.0,
            "p95_runtime_ms": 0.0,
            "p99_runtime_ms": 0.0,
        }
    recalls10, recalls20, ndcgs = [], [], []
    cross_total = cross_count = available_count = item_count = 0
    seen_products: set[str] = set()
    for user in users:
        rows = list(recommendations[user])
        ids = [_product_id(row) for row in rows]
        target = targets[user]
        recalls10.append(float(target in ids[:10]))
        recalls20.append(float(target in ids[:20]))
        reciprocal = 0.0
        if target in ids[:10]:
            reciprocal = 1.0 / np.log2(ids[:10].index(target) + 2)
        ndcgs.append(reciprocal)
        bought = purchased_taxonomies.get(user, set())
        for product_id in ids[:20]:
            product_index = index.idx.get(product_id)
            if product_index is None:
                continue
            seen_products.add(product_id)
            item_count += 1
            available_count += int(bool(index.available[product_index]))
            cross_total += 1
            cross_count += int(str(index.taxonomy[product_index]) not in bought)
    recommendable_count = max(int(np.asarray(index.recommendable, dtype=bool).sum()), 1)
    latencies = np.asarray(latencies_ms or [], dtype=np.float64)
    return {
        "recall@10": float(np.mean(recalls10)),
        "recall@20": float(np.mean(recalls20)),
        "ndcg@10": float(np.mean(ndcgs)),
        "cross_category_rate": cross_count / cross_total if cross_total else 0.0,
        "availability_precision": available_count / item_count if item_count else 0.0,
        "catalog_coverage": len(seen_products) / recommendable_count,
        "p95_runtime_ms": float(np.percentile(latencies, 95)) if latencies.size else 0.0,
        "p99_runtime_ms": float(np.percentile(latencies, 99)) if latencies.size else 0.0,
    }


def _purchased_taxonomies(split: LeaveOnePurchaseOut, index: UnitIndex) -> dict[str, set[str]]:
    result: dict[str, set[str]] = {}
    for user, events in split.train_by_user.items():
        purchases = [event for event in events if event.get("eventName") == "purchase"]
        if not purchases:
            result[user] = set()
            continue
        latest_group = max(purchases, key=lambda event: _time_key(event, 0)).get("eventGroupId")
        relevant = [event for event in purchases if event.get("eventGroupId") == latest_group] if latest_group else purchases
        categories = set()
        for event in relevant:
            item = index.resolve(str(event.get("productId") or ""))
            if item is not None:
                categories.add(str(index.taxonomy[item]))
        result[user] = categories
    return result


def run_benchmark(index: UnitIndex, events: list[dict], k: int = 20, seed: int = 42) -> tuple[list[dict], LeaveOnePurchaseOut]:
    """Fit every method on the common training snapshot and compare identical users."""
    split = leave_one_purchase_out(events, index)
    if not split.targets:
        raise ValueError("Không có purchase hợp lệ để tạo temporal holdout.")
    models = build_recommenders(index, split.train_events)
    categories = _purchased_taxonomies(split, index)
    output = []
    for model in models:
        predictions: dict[str, list[RankedProduct]] = {}
        latencies = []
        for user in sorted(split.targets):
            started = time.perf_counter()
            predictions[user] = model.recommend(user, split.train_by_user.get(user, []), k=k, seed=seed)
            latencies.append((time.perf_counter() - started) * 1000)
        metrics = score_recommendations(predictions, split.targets, categories, index, latencies)
        output.append({"key": model.key, "label": model.label, "limitation": model.limitation, **metrics})
    return output, split
